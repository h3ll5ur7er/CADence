// Credits for the libraries and fonts CADence ships: the production dependencies of package.json and
// theirs, read from node_modules. `node tools/licences/licences.mjs` writes the About dialog's list
// (src/app/about/credits.ts) and the full licence texts (public/third-party-licences.txt); a test
// checks both are current.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const outputs = { credits: join(root, 'src', 'app', 'about', 'credits.ts'), texts: join(root, 'public', 'third-party-licences.txt') };

const readJson = (path) => JSON.parse(readFileSync(path, 'utf8'));

/** Where Node would find a package from `from` (a package folder). */
function resolvePackage(name, from) {
  for (let dir = from; ; dir = dirname(dir)) {
    const candidate = join(dir, 'node_modules', name);
    if (existsSync(join(candidate, 'package.json'))) return candidate;
    if (dirname(dir) === dir) return undefined;
  }
}

function sourceUrl(pkg) {
  const repository = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url;
  if (!repository) return pkg.homepage ?? `https://www.npmjs.com/package/${pkg.name}`;
  if (/^github:|^[\w-]+\/[\w.-]+$/.test(repository)) return `https://github.com/${repository.replace(/^github:/, '')}`;
  return repository.replace(/^git\+/, '').replace(/^git:\/\//, 'https://').replace(/^ssh:\/\/git@/, 'https://').replace(/^git@([^:]+):/, 'https://$1/').replace(/\.git$/, '');
}

const licenceFile = (dir) => readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(f));

/** Every production package, once, sorted by name. */
export function collect() {
  const app = readJson(join(root, 'package.json'));
  const found = new Map();
  const visit = (name, from) => {
    const dir = resolvePackage(name, from);
    if (!dir) return;
    const pkg = readJson(join(dir, 'package.json'));
    const key = `${pkg.name}@${pkg.version}`;
    if (found.has(key)) return;
    const file = licenceFile(dir);
    found.set(key, {
      name: pkg.name,
      version: pkg.version,
      license: typeof pkg.license === 'string' ? pkg.license : (pkg.license?.type ?? 'see its licence file'),
      url: sourceUrl(pkg),
      text: file ? readFileSync(join(dir, file), 'utf8').replace(/\r\n/g, '\n').trim() : undefined,
    });
    for (const dependency of Object.keys({ ...pkg.dependencies, ...pkg.optionalDependencies })) visit(dependency, dir);
  };
  for (const name of Object.keys(app.dependencies)) visit(name, root);
  return { version: app.version, packages: [...found.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version)) };
}

export function render({ version, packages }) {
  const list = packages.map(({ name, version, license, url }) => ({ name, version, license, url }));
  const credits = `// Generated by tools/licences/licences.mjs from package.json and node_modules; do not edit.

/** The app's version. */
export const appVersion = ${JSON.stringify(version)};

/** Every library and font CADence ships, with its licence. */
export const credits: readonly { readonly name: string; readonly version: string; readonly license: string; readonly url: string }[] = ${JSON.stringify(list, null, 2)};
`;
  const texts = `Third-party software in CADence ${version}

CADence ships the libraries and fonts below. Each is listed with its version, licence and source,
followed by the text of its licence.

OpenCascade (replicad-opencascadejs) and planegcs are used under the GNU Lesser General Public
License: they are loaded as separate WebAssembly files, which may be replaced by modified versions,
and their sources are available at the addresses given.

${packages
  .map(({ name, version, license, url, text }) => `${'='.repeat(78)}\n${name} ${version} (${license})\n${url}\n\n${text ?? `Licensed under ${license}; no licence file is included in the package.`}\n`)
  .join('\n')}`;
  return { credits, texts };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { credits, texts } = render(collect());
  writeFileSync(outputs.credits, credits);
  writeFileSync(outputs.texts, texts);
  console.log(`Credits for ${collect().packages.length} packages written.`);
}
